  // ===========================================================================
  // PROTOCOL MESSAGE TYPE HEADERS (3-bit Type Field in OptiBolt Frame Header)
  // ===========================================================================

  /**
   * MSG_CAPABILITIES (3'b000)
   * -------------------------
   * Purpose: Link Handshake, Challenge-Response, and Loopback detection.
   * Data payload: [7:0] Challenge token generated by PRNG.
   *  - Differentiates DISCONNECTED (no light), CONNECTED (peer echoed token),
   *    and LOOPBACK (received own token).
   */
  localparam logic [2:0] MSG_CAPABILITIES = 3'b000;

  /**
   * MSG_REQUEST (3'b001)
   * --------------------
   * Purpose: Link Control Requests, Commands, and Speed Negotiation ACKs.
   * Submessages & Data payload:
   *  - CMD_PING_REQ    (8'hA5) : Ping RTT Measurement Request
   *  - CMD_PING_RESP   (8'h5A) : Ping RTT Measurement Response (replies to A5)
   *  - CMD_SWEEP_START (8'hE0) : Sweep Test Sequence Start Notification
   *  - CMD_SWEEP_END   (8'hE1) : Sweep Test Sequence End Notification (revert to 1.0M)
   *  - CMD_SPEED_ACK   (8'hB1) : Speed Negotiation Acknowledged (peer accepted rate)
   *  - Speed Nego Req  {OS[3:0], BAUD[3:0]} : Speed Negotiation Request
   *      OS:   4'd0 = 8x OS, 4'd1 = 16x OS
   *      BAUD: 4'd0=100k, 4'd1=1M, 4'd2=1.25M, 4'd3=2.5M, 4'd4=3.125M,
   *            4'd5=5M, 4'd6=6.25M, 4'd7=8.33M, 4'd8=12.5M, 4'd9=25M
   */
  localparam logic [2:0] MSG_REQUEST = 3'b001;

  /**
   * MSG_ACCEPT (3'b010)
   * -------------------
   * Purpose: Optical Link Handshake Response ACK.
   * Data payload: [7:0] Echo of peer challenge token confirming duplex connection.
   */
  localparam logic [2:0] MSG_ACCEPT = 3'b010;

  /**
   * MSG_DENIED (3'b011)
   * -------------------
   * Purpose: Command Rejection / Protocol NACK.
   */
  localparam logic [2:0] MSG_DENIED = 3'b011;

  /**
   * MSG_TEXT (3'b100)
   * -----------------
   * Purpose: Console ASCII Text Messaging (Chat).
   * Data payload: [7:0] ASCII Character byte (e.g. 'A'..'Z', '0'..'9', '\n').
   */
  localparam logic [2:0] MSG_TEXT = 3'b100;

  /**
   * MSG_BITMAP (3'b101)
   * -------------------
   * Purpose: Dynamic 128x128 12-bit RGB PRNG Bitmap Streaming (2 bytes per pixel).
   * Submessage pixel framing:
   *  - Byte 0: {1'b0, R[3:0], G[3:1]}
   *      Bit 7 = 1'b0 : Header indicating Byte 0 of pixel
   *      Bits [6:3]   : 4-bit Red channel (0..15)
   *      Bits [2:0]   : Top 3 bits of Green channel (G[3:1])
   *  - Byte 1: {1'b1, G[0], B[3:0], 2'b00}
   *      Bit 7 = 1'b1 : Header indicating Byte 1 of pixel
   *      Bit 6        : Bottom bit of Green channel (G[0])
   *      Bits [5:2]   : 4-bit Blue channel (0..15)
   *      Bits [1:0]   : 2'b00 (Zero padding)
   */
  localparam logic [2:0] MSG_BITMAP = 3'b101;

  /**
   * MSG_POWER (3'b110)
   * ------------------
   * Purpose: Multi-profile Power Negotiation & Capability Exchange.
   * Submessages & Data payload:
   *  - Offer/Request  {role[1:0], volt_id[1:0], amps[3:0]}:
   *      role:    2'd0=NONE, 2'd1=WALL, 2'd2=BATTERY, 2'd3=SINK
   *      volt_id: 2'd0=5V,   2'd1=9V,   2'd2=12V,    2'd3=20V
   *      amps:    4-bit required/supplied current in Amperes (0..9A)
   *  - Teardown:      (8'hFE) : Power Contract Release / Power OFF
   *  - Contract ACK:  (8'hFD) : Contract established confirmation
   *  - Conflict/Err:  (8'hFC) : Power collision or invalid configuration
   */
  localparam logic [2:0] MSG_POWER = 3'b110;

  /**
   * MSG_SWEEP (3'b111)
   * ------------------
   * Purpose: Baudrate Sweep Link Verification & Packet Echo.
   * Data payload: {sweep_step[3:0], sweep_tx_count[3:0]}
   *  - Bits [7:4]: Sweep test step index (0..15)
   *  - Bits [3:0]: Test packet sequence counter (0..15)
   *  - Responder echoes the packet back verbatim to test duplex BER and packet delivery.
   */
  localparam logic [2:0] MSG_SWEEP = 3'b111;

  // Control Constants for MSG_REQUEST
  localparam logic [7:0] CMD_PING_REQ = 8'hA5;
  localparam logic [7:0] CMD_PING_RESP = 8'h5A;
  localparam logic [7:0] CMD_SWEEP_START = 8'hE0;
  localparam logic [7:0] CMD_SWEEP_END = 8'hE1;
  localparam logic [7:0] CMD_SPEED_ACK = 8'hB1;

endpackage
